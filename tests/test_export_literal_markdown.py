"""Export literal researcher text without promoting escaped syntax or code."""

import html
import re
from html.parser import HTMLParser

import pytest
from docx import Document

from rde.domain.models.report import EDAReport, ReportSection
from rde.infrastructure.adapters.docx_exporter import DocxExporter


def report(content):
    return EDAReport(
        id="literal",
        dataset_id="d1",
        project_id="p1",
        title="Literal statement",
        sections=[ReportSection("methods", "Methods", content)],
    )


class HtmlText(HTMLParser):
    def __init__(self, content):
        super().__init__()
        self.parts = []
        self.feed(content)

    def handle_data(self, data):
        self.parts.append(data)


def test_escaped_researcher_text_survives_docx_and_html_without_formatting(tmp_path):
    original = r"D-penicillamine, *literal* [group_1] < reference & x; C:\data\study."
    # This is the public execution_markdown escaping convention, not a new
    # replacement plan or source statement generated by the exporter.
    escaped = re.sub(r"([\\`*_{}\[\]()#+.!|>-])", r"\\\1", html.escape(original, quote=False))
    data = report(escaped)
    before = data.sections[0].content
    exporter = DocxExporter()
    doc = Document(exporter.export_docx(data, tmp_path / "literal.docx"))
    paragraph = next(p for p in doc.paragraphs if "penicillamine" in p.text)
    assert paragraph.text == original
    assert all(not r.bold and not r.italic for r in paragraph.runs)
    rendered = exporter._build_pdf_html(data)
    assert original in "".join(HtmlText(rendered).parts)
    assert "<strong>literal" not in rendered and "<em>literal" not in rendered
    assert "&lt; reference" in rendered
    assert data.sections[0].content == before


def test_emphasis_code_and_real_backslashes_are_distinct_runs(tmp_path):
    content = r"**Actual bold**; \*literal\*; *actual italic*; C:\folder\file; `a\*b &lt; **code**`; ``x`y\z``"
    doc = Document(DocxExporter().export_docx(report(content), tmp_path / "runs.docx"))
    p = next(p for p in doc.paragraphs if "Actual bold" in p.text)
    assert "*literal*" in p.text
    assert r"C:\folder\file" in p.text
    assert r"a\*b &lt; **code**" in p.text and r"x`y\z" in p.text
    assert next(r for r in p.runs if r.text == "Actual bold").bold
    assert next(r for r in p.runs if r.text == "actual italic").italic
    code = next(r for r in p.runs if r.text == r"a\*b &lt; **code**")
    assert code.font.name == "Courier New" and not code.bold and not code.italic
    html_text = DocxExporter._md_to_html_inline(content)
    assert "<strong>Actual bold</strong>" in html_text
    assert "<em>actual italic</em>" in html_text
    assert r"<code>a\*b &amp;lt; **code**</code>" in html_text
    assert "*literal*" in html_text


def test_heading_inherits_style_unless_inline_emphasis_explicit(tmp_path):
    doc = Document(
        DocxExporter().export_docx(
            report("### Ordinary **explicit** and *italic*"), tmp_path / "heading.docx"
        )
    )
    heading = next(p for p in doc.paragraphs if p.text == "Ordinary explicit and italic")
    assert heading.style.name == "Heading 3" and heading.style.font.bold is True
    ordinary = next(r for r in heading.runs if r.text == "Ordinary ")
    assert ordinary.bold is None and ordinary.italic is None
    assert next(r for r in heading.runs if r.text == "explicit").bold is True
    assert next(r for r in heading.runs if r.text == "italic").italic is True


@pytest.mark.parametrize("fence", ["```", "````", "~~~"])
def test_fenced_code_is_literal_in_word_and_pdf_html(tmp_path, fence):
    code = r"\*literal\* **not bold** C:\data\file <tag> &lt;" + "  "
    content = f"{fence}text\n{code}\n{fence}\nAfter D\\-drug"
    exporter = DocxExporter()
    data = report(content)
    doc = Document(exporter.export_docx(data, tmp_path / "code.docx"))
    paragraph = next(p for p in doc.paragraphs if "not bold" in p.text)
    assert paragraph.text == code
    assert paragraph.runs[0].font.name == "Courier New"
    assert not paragraph.runs[0].bold
    rendered = exporter._build_pdf_html(data)
    assert "<pre><code>" + html.escape(code) + "</code></pre>" in rendered
    assert "After D-drug" in "".join(HtmlText(rendered).parts)


def test_escaped_pipe_table_and_headings_lists_use_literal_text(tmp_path):
    content = (
        r"### D\-drug \*label\*"
        + "\n"
        + r"- Keep \[A\] and C:\data"
        + "\n\n"
        + r"| Group \| label | Code |"
        + "\n| --- | --- |\n"
        + r"| A\|B | `x|y\z` |"
    )
    exporter = DocxExporter()
    data = report(content)
    doc = Document(exporter.export_docx(data, tmp_path / "table.docx"))
    assert any(p.text == "D-drug *label*" for p in doc.paragraphs)
    assert any(p.text == r"Keep [A] and C:\data" for p in doc.paragraphs)
    assert [[c.text for c in row.cells] for row in doc.tables[0].rows] == [
        ["Group | label", "Code"],
        ["A|B", r"x|y\z"],
    ]
    rendered = exporter._build_pdf_html(data)
    assert "<th>Group | label</th>" in rendered
    assert r"<td><code>x|y\z</code></td>" in rendered


@pytest.mark.parametrize(
    "text",
    ["trailing\\", "`unclosed", "*unclosed", r"C:\data\value", r"\*not emphasis\*", "**plain**"],
)
def test_inline_plain_word_and_html_have_same_visible_text(text):
    visible = DocxExporter._strip_md_formatting(text)
    rendered = DocxExporter._md_to_html_inline(text)
    assert "".join(HtmlText(rendered).parts) == visible
